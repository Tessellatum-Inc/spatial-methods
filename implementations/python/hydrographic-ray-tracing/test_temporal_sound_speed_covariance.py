import math

import pytest

from temporal_sound_speed_covariance import (
    build_temporally_correlated_sound_speed_covariance,
)


def test_single_epoch_covariance_is_preserved_exactly():
    profile = [[4.0, 1.0], [1.0, 9.0]]
    result = build_temporally_correlated_sound_speed_covariance(
        [12.0], profile, 30.0
    )
    assert result["joint_profile_covariance"] == profile
    assert result["temporal_correlation"] == [[1.0]]


def test_temporal_covariance_uses_exponential_correlation_and_epoch_major_order():
    profile = [[4.0, 1.0], [1.0, 9.0]]
    result = build_temporally_correlated_sound_speed_covariance(
        [0.0, 10.0], profile, 20.0
    )
    rho = math.exp(-0.5)
    expected = [
        [4.0, 1.0, 4.0 * rho, rho],
        [1.0, 9.0, rho, 9.0 * rho],
        [4.0 * rho, rho, 4.0, 1.0],
        [rho, 9.0 * rho, 1.0, 9.0],
    ]
    for actual_row, expected_row in zip(
        result["joint_profile_covariance"], expected
    ):
        assert actual_row == pytest.approx(expected_row)


def test_temporal_covariance_is_symmetric_and_positive_semidefinite():
    profile = [[4.0, 1.0], [1.0, 9.0]]
    result = build_temporally_correlated_sound_speed_covariance(
        [4.0, 0.0, 7.0, 4.0], profile, 15.0
    )
    covariance = result["joint_profile_covariance"]
    assert all(
        covariance[i][j] == pytest.approx(covariance[j][i])
        for i in range(len(covariance))
        for j in range(len(covariance))
    )
    # Every quadratic form generated by the covariance must be non-negative.
    vector = [1.0, -2.0, 0.5, 3.0, -1.0, 0.25, 2.0, -0.5]
    quadratic_form = sum(
        vector[i] * covariance[i][j] * vector[j]
        for i in range(len(vector)) for j in range(len(vector))
    )
    assert quadratic_form >= -1e-10


def test_temporal_covariance_permutation_preserves_epoch_association():
    profile = [[2.0, 0.25], [0.25, 3.0]]
    forward = build_temporally_correlated_sound_speed_covariance(
        [0.0, 5.0, 12.0], profile, 8.0
    )["joint_profile_covariance"]
    reverse = build_temporally_correlated_sound_speed_covariance(
        [12.0, 5.0, 0.0], profile, 8.0
    )["joint_profile_covariance"]
    permutation = [4, 5, 2, 3, 0, 1]
    for i in range(6):
        for j in range(6):
            assert reverse[i][j] == pytest.approx(
                forward[permutation[i]][permutation[j]]
            )


@pytest.mark.parametrize(
    "epochs,profile,tau",
    [
        ([], [[1.0]], 1.0),
        ([0.0, math.inf], [[1.0]], 1.0),
        ([0.0], [[1.0]], 0.0),
        ([0.0], [[1.0]], math.nan),
        ([0.0], [[1.0, 0.0]], 1.0),
        ([0.0], [[1.0, 2.0], [0.0, 1.0]], 1.0),
        ([0.0], [[1.0, 0.0], [0.0, -1.0]], 1.0),
    ],
)
def test_invalid_temporal_profile_inputs_are_rejected(epochs, profile, tau):
    with pytest.raises(ValueError):
        build_temporally_correlated_sound_speed_covariance(
            epochs, profile, tau
        )


def test_increasing_time_separation_reduces_cross_epoch_covariance():
    result = build_temporally_correlated_sound_speed_covariance(
        [0.0, 10.0, 100.0], [[4.0]], 20.0
    )
    covariance = result["joint_profile_covariance"]
    assert covariance[0][1] == pytest.approx(4.0 * math.exp(-0.5))
    assert covariance[0][2] == pytest.approx(4.0 * math.exp(-5.0))
    assert covariance[0][1] > covariance[0][2]
